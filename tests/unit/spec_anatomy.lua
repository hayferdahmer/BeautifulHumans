describe("Anatomy", function()
    it("maps the 17 engine zones to stable logical ids", function()
        eq(BH.Anatomy.Zones.Count(), 17)
        truthy(BH.Anatomy.Zones.Get("head"))
        truthy(BH.Anatomy.Zones.Get("left_forearm"))
        truthy(BH.Anatomy.Zones.Get("right_foot"))
        eq(BH.Anatomy.Zones.Get("head").fallback, 8)
        eq(BH.Anatomy.Zones.Get("left_hand").fallback, 0)
    end)

    it("keeps multiple injuries in one zone distinct", function()
        local data = BH.Persistence.NewCharacterData()
        local first = BH.Anatomy.Model.AddInjury(data, "left_thigh", "cut", 40, "debug")
        local second = BH.Anatomy.Model.AddInjury(data, "left_thigh", "fracture", 60, "fall")
        truthy(first)
        truthy(second)
        ne(first.id, second.id)
        eq(BH.Anatomy.Model.GetZoneState(data, "left_thigh").injuries[first.id], first)
        eq(BH.Anatomy.Model.GetZoneState(data, "left_thigh").injuries[second.id], second)
    end)

    it("caps impairment instead of producing negative capacity", function()
        local data = BH.Persistence.NewCharacterData()
        BH.Anatomy.Model.AddInjury(data, "left_thigh", "fracture", 100, "fall")
        BH.Anatomy.Model.AddInjury(data, "left_thigh", "deep_wound", 100, "weapon")
        BH.Anatomy.Model.AddInjury(data, "left_thigh", "burn", 100, "environment")
        local impairment = BH.Anatomy.Model.GetZoneImpairment(data, "left_thigh")
        truthy(impairment > 0)
        truthy(impairment <= 0.95)
        truthy(BH.Anatomy.Model.GetMobility(data) >= 0.05)
    end)

    it("reduces mobility when both legs are injured", function()
        local data = BH.Persistence.NewCharacterData()
        local healthy = BH.Anatomy.Model.GetMobility(data)
        BH.Anatomy.Model.AddInjury(data, "left_thigh", "fracture", 80, "fall")
        BH.Anatomy.Model.AddInjury(data, "right_thigh", "fracture", 80, "fall")
        local injured = BH.Anatomy.Model.GetMobility(data)
        truthy(injured < healthy)
        truthy(injured >= 0.05)
    end)

    it("reduces manipulation for hand injuries", function()
        local data = BH.Persistence.NewCharacterData()
        local healthy = BH.Anatomy.Model.GetManipulation(data)
        BH.Anatomy.Model.AddInjury(data, "right_hand", "deep_wound", 90, "weapon")
        local injured = BH.Anatomy.Model.GetManipulation(data)
        truthy(injured < healthy)
        truthy(injured >= 0.10)
    end)

    it("ticks bleeding down and eventually heals a minor wound", function()
        local data = BH.Persistence.NewCharacterData()
        local injury = BH.Anatomy.Model.AddInjury(data, "left_forearm", "abrasion", 20, "debug")
        truthy(injury.bleeding > 0)
        local before = injury.bleeding
        BH.Anatomy.Model.Tick(data, 5)
        truthy(injury.bleeding < before)

        local healed = BH.Anatomy.Model.Tick(data, 5000)
        truthy(healed >= 1)
        eq(BH.Anatomy.Model.FindInjury(data, injury.id), nil)
    end)

    it("merges at the per-zone cap rather than growing without bound", function()
        BH.Config.Reset({ maxInjuriesPerZone = 2 })
        local data = BH.Persistence.NewCharacterData()
        BH.Anatomy.Model.AddInjury(data, "abdomen", "cut", 30, "debug")
        BH.Anatomy.Model.AddInjury(data, "abdomen", "cut", 30, "debug")
        BH.Anatomy.Model.AddInjury(data, "abdomen", "cut", 30, "debug")

        local zoneState = BH.Anatomy.Model.GetZoneState(data, "abdomen")
        local count = 0
        for _ in pairs(zoneState.injuries) do
            count = count + 1
        end
        eq(count, 2)
        BH.Config.Reset()
    end)

    it("returns deterministic functional modifiers", function()
        local data = BH.Persistence.NewCharacterData()
        eq(BH.Anatomy.Model.GetMobility(data), 1)
        eq(BH.Anatomy.Model.GetManipulation(data), 1)
        eq(BH.Anatomy.Model.GetConsciousness(data), 1)
        eq(BH.Anatomy.Model.GetRespiration(data), 1)
    end)
end)
