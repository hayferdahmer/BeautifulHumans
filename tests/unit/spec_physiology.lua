describe("Physiology", function()
    it("derives pain and blood-loss load from injuries", function()
        local data = BH.Persistence.NewCharacterData()
        eq(data.physiology.pain, 0)
        BH.Anatomy.Model.AddInjury(data, "left_thigh", "deep_wound", 80, "weapon")
        truthy(data.physiology.pain > 0)
        truthy(data.physiology.bloodLoss > 0)
    end)

    it("reduces capacity without zeroing it", function()
        local data = BH.Persistence.NewCharacterData()
        local healthy = BH.Physiology.GetCapacity(data)
        BH.Anatomy.Model.AddInjury(data, "head", "fracture", 90, "fall")
        BH.Anatomy.Model.AddInjury(data, "chest", "deep_wound", 90, "weapon")
        local injured = BH.Physiology.GetCapacity(data)
        truthy(injured < healthy)
        truthy(injured >= 0)
    end)

    it("smooths pain towards its target", function()
        local data = BH.Persistence.NewCharacterData()
        BH.Anatomy.Model.AddInjury(data, "right_forearm", "burn", 80, "environment")
        local before = data.physiology.pain
        BH.Physiology.Tick(data, 1)
        truthy(data.physiology.pain <= before)
        BH.Physiology.Tick(data, 60)
        truthy(BH.Physiology.GetModifiers(data).pain >= 0)
    end)
end)
